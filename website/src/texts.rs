/// The texts of the page in a language: English text to translation.
pub fn translations(lang: Lang) -> Value {
    let map: Map<String, Value> = TEXTS.iter().map(|en| ((*en).to_string(), Value::String(translate(en, lang).to_string()))).collect();
    Value::Object(map)
}

