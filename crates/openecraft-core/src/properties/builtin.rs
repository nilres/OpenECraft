#[derive(Clone, Copy)]
pub(super) struct Row {
    pub key: &'static str,
    pub name: &'static str,
    pub class: ObjectClass,
    pub group: Group,
    pub ty: DataType,
    pub unit: &'static str,
    pub choices: &'static [&'static str],
    pub indices: u16,
    /// Computed or taken from the model; values cannot be stored.
    pub read_only: bool,
    /// Taken from a field of the model (device description, page name …): can be
    /// changed, but is not stored in the property values.
    pub field: bool,
    /// Property of the same object used while no value is set (e.g. part data).
    pub fallback: &'static str,
}

const fn r(key: &'static str, name: &'static str, class: ObjectClass, group: Group, ty: DataType, unit: &'static str) -> Row {
    Row { key, name, class, group, ty, unit, choices: &[], indices: 0, read_only: false, field: false, fallback: "" }
}

impl Row {
    const fn ro(mut self) -> Row {
        self.read_only = true;
        self
    }
    const fn field(mut self) -> Row {
        self.field = true;
        self
    }
    const fn of(mut self, choices: &'static [&'static str]) -> Row {
        self.choices = choices;
        self
    }
    const fn idx(mut self, n: u16) -> Row {
        self.indices = n;
        self
    }
    const fn or(mut self, fallback: &'static str) -> Row {
        self.fallback = fallback;
        self
    }
}

